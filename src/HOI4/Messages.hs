-- | Convert a list of messages zipped with their indentation levels to a Doc.
-- Each message is prepended with a number of asterisks (levels of bullet
-- list) equal to its indentation level.

-- | Capitalize a label for the front of a sentence without touching the rest of
-- it. A flag type is a common noun -- "unit leader" -- and title-casing every
-- word of it leaves a capital stranded mid-sentence wherever the label is read
-- on from a heading and its first letter lowered again.
capitalise :: Text -> Text
capitalise t = case T.uncons t of
    Just (c, rest) -> T.cons (toUpper c) rest
    Nothing -> t

imsg2doc :: (IsGameData (GameData g), Monad m) => IndentedMessages -> PPT g m Doc
imsg2doc msgs = do
    said <- mapM (\(i, rm) -> (,) i <$> messageText rm) msgs
    return . PP.vsep $
        [ PP.hsep [Doc.strictText (T.replicate i "*"), Doc.strictText line]
        | (i, line) <- rollUpStates said ]

-- | Draw together a run of lines that each say the very same thing of a single
-- state, so that the states are named in one go rather than a line apiece.
-- Script writes such a run out state by state, where the game names them
-- together, and a column of lines alike but for the state in them is a column
-- the reader has to go down to find what little differs.
--
-- Only lines with nothing written under them are drawn together. A line with a
-- list of its own under it is a heading, and two headings saying the same need
-- not head the same thing; those are 'HOI4.SpecialHandlers.chunkStates' to draw
-- together, where what stands under them can be seen.
rollUpStates :: [(Int, Text)] -> [(Int, Text)]
rollUpStates said = map rejoin (groupBy alike (zip said standalone))
    where
        -- A line is a heading if the line after it is written deeper than it is.
        standalone = zipWith (\(i, _) mnext -> maybe True (<= i) mnext)
                             said
                             (map (Just . fst) (drop 1 said) ++ [Nothing])
        alike ((i, one), aloneone) ((j, two), alonetwo) =
            aloneone && alonetwo && i == j && case (oneState one, oneState two) of
                (Just (beforeone, _, afterone), Just (beforetwo, _, aftertwo)) ->
                    beforeone == beforetwo && afterone == aftertwo
                _ -> False
        rejoin run@(((i, line), _) : _ : _)
            | Just (before, _, after) <- oneState line
            = (i, mconcat
                [ before
                , Doc.doc2text (template "states" (mapMaybe stateOf run))
                , after
                ])
        rejoin (((i, line), _) : _) = (i, line)
        rejoin [] = (0, "")
        stateOf ((_, line), _) = (\(_, sid, _) -> sid) <$> oneState line

-- | A line that names a single state, split into what it says before that state,
-- the state's id, and what it says after. A line naming no state, or naming
-- more than one, is none of these: what such a line says of each of them is not
-- said by naming them together.
oneState :: Text -> Maybe (Text, Text, Text)
oneState line = case T.breakOn stateOpen line of
    (before, rest) | not (T.null rest) ->
        case T.breakOn "}}" (T.drop (T.length stateOpen) rest) of
            (sid, closing)
                | not (T.null sid), T.all isDigit sid, not (T.null closing)
                , let after = T.drop 2 closing
                , not (stateOpen `T.isInfixOf` after)
                -> Just (before, sid, after)
            _ -> Nothing
    _ -> Nothing
    where stateOpen = "{{state|"

-- | As 'imsg2doc', but use HTML to format the messages instead of wiki markup.
-- This behaves better with <pre> blocks but doesn't play well with idea
-- groups.
-- | One entry of an html list: a message on its own, or an effect box together
-- with the lines it lists and the message that closes it.
data HtmlItem = HtmlMsg ScriptMessage | HtmlBox ScriptMessage IndentedMessages [ScriptMessage]

imsg2doc_html :: forall g m. (IsGameData (GameData g), Monad m) => IndentedMessages -> PPT g m Doc
imsg2doc_html [] = return mempty
imsg2doc_html msgs
    | base > 0  = PP.enclose "<ul>" "</ul>" <$> items base grouped
    | otherwise = items base grouped
    where
        grouped = group 1 msgs
        -- Start from the shallowest entry there is, so that 'items' never meets
        -- one shallower than the level it was asked for and drops it. This is
        -- read off the grouped entries rather than the messages: an effect box
        -- is written at a level of its own, having to break out of a wiki list
        -- in the other rendering, and so are the lines inside it, none of which
        -- says anything about how deep the list it stands in goes.
        base = case map fst grouped of
            [] -> 1
            levels -> minimum levels
        isBoxEnd MsgEffectBoxEnd {} = True
        isBoxEnd _ = False

        -- Bundle each effect box with the lines inside it. A box is one template
        -- call written out over several messages, the modifiers it lists being
        -- an argument of that call, so a list item opened or closed in the
        -- middle would break the call apart. The run stands at the level of
        -- whatever came before it, which is what it belongs beside.
        group :: Int -> IndentedMessages -> [(Int, HtmlItem)]
        group _ [] = []
        group lvl ((_, msg@MsgEffectBox {}) : rest) =
            let (inner, after) = break (isBoxEnd . snd) rest
                (end, rest') = splitAt 1 after
            in (lvl, HtmlBox msg inner (map snd end)) : group lvl rest'
        -- The end of a box with no beginning to it, which should not happen and
        -- must not be allowed to pull the list it lands in out of shape.
        group lvl ((_, msg@MsgEffectBoxEnd {}) : rest) = (lvl, HtmlMsg msg) : group lvl rest
        group _ ((i, msg) : rest) = (i, HtmlMsg msg) : group i rest

        entry :: HtmlItem -> PPT g m Doc
        entry (HtmlMsg msg) = message msg
        entry (HtmlBox msg inner end) = do
            headd <- message msg
            innerd <- imsg2doc_html inner
            endd <- mconcat <$> mapM message end
            return (headd <> innerd <> endd)

        -- Format every entry at the given level, each with the deeper ones
        -- following it nested underneath, and stop at the first one shallower
        -- than the level, which belongs to whoever asked.
        items :: Int -> [(Int, HtmlItem)] -> PPT g m Doc
        items _ [] = return mempty
        items lvl ((i, it):its)
            | i < lvl = return mempty
            | otherwise = do
                m <- entry it
                -- Everything deeper than this entry, up to the next one at
                -- this level or shallower, is what goes under it.
                let (deeper, rest) = span ((> lvl) . fst) its
                nested <- case deeper of
                    [] -> return mempty
                    ((i',_):_) -> PP.enclose "<ul>" "</ul>" <$> items i' deeper
                post <- items lvl rest
                return (PP.enclose "<li>" "</li>" (m <> nested) <> post)
